"""Generate the per-method section of COVERAGE.md from the installed README + the live Resolve.

For every method documented in README.txt it records: whether the live object really has it,
which typed MCP tool uses it (else: reachable through api_call), and deprecated/unsupported flags.
Needs the bridge running and a project with at least one timeline item (run tests/run_tests.py first).

    .venv\\Scripts\\python.exe tools\\gen_coverage.py > docs\\coverage_methods.md
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "server"))

import catalog  # noqa: E402
import core  # noqa: E402

src = open(os.path.join(ROOT, "server", "mcp_server.py"), encoding="utf-8").read()
src += open(os.path.join(ROOT, "server", "workarounds.py"), encoding="utf-8").read()
src += open(os.path.join(ROOT, "bridge", "bridge_core.py"), encoding="utf-8").read()


def tools_using(method):
    """Typed tools whose body mentions the method name as a string literal or attribute."""
    out = []
    for m in re.finditer(r"@server\.tool\([^)]*\)\s*def (\w+)\((.*?)(?=\n@server\.tool|\nif __name__)", src, re.S):
        if re.search(r"[\"'.]%s[\"'(]" % re.escape(method), m.group(2)):
            out.append(m.group(1))
    if not out and re.search(r"\b%s\b" % re.escape(method), src):
        out.append("(state snapshot / workaround)")
    return out


def live_handles():
    r = core.roots()
    hs = {"Resolve": "resolve", "ProjectManager": r["project_manager"], "Project": r["project"],
          "MediaPool": r["media_pool"], "Folder": r["root_folder"], "MediaStorage": r["media_storage"],
          "Gallery": r["gallery"], "Timeline": r["timeline"]}
    tl = r["timeline"]
    item = None
    for i in range(1, (core.get(tl, "GetTrackCount", "video") or 0) + 1):
        items = core.get(tl, "GetItemListInTrack", "video", i) or []
        if items:
            item = items[0]
            break
    hs["TimelineItem"] = item
    if item:
        hs["MediaPoolItem"] = core.get(item, "GetMediaPoolItem")
        hs["Graph"] = core.get(item, "GetNodeGraph")
    alb = core.get(r["gallery"], "GetCurrentStillAlbum")
    hs["GalleryStillAlbum"] = alb
    groups = core.get(r["project"], "GetColorGroupsList") or []
    hs["ColorGroup"] = groups[0] if groups else None
    return hs


def main():
    cat = catalog.get_catalog()
    hs = live_handles()
    live = {}
    for cls, h in hs.items():
        if h:
            live[cls] = set(core.B.request("methods", target=core.handle_id(h))["methods"])
    ver = core.B.request("ping")["version"]
    print("## Method-level coverage (generated)\n")
    print("Generated by `tools/gen_coverage.py` from `%s` against live Resolve %s.\n" % (cat["path"], ver))
    print("Every documented method is callable through `api_call` (catalog-checked, read-back verified where a getter "
          "exists). The *Typed tool* column lists the dedicated tools that wrap it.\n")
    totals = {"documented": 0, "live": 0, "typed": 0}
    for cls, methods in cat["classes"].items():
        if not methods:
            continue
        print("### %s\n" % cls)
        print("| Method | In live %s? | Typed tool(s) | Notes |" % ver)
        print("|---|---|---|---|")
        for m, e in sorted(methods.items()):
            notes = []
            if e.get("deprecated"):
                notes.append("deprecated")
            if e.get("unsupported"):
                notes.append("unsupported")
            if e.get("unsupported_signatures"):
                notes.append("index-based overloads unsupported")
            if re.search(r"Studio and AI Scripting APIs", e.get("doc", "")):
                notes.append("Studio/AI prerequisites")
            lv = live.get(cls)
            present = "?" if lv is None else ("yes" if m in lv else "**no**")
            typed = tools_using(m)
            totals["documented"] += 1
            totals["live"] += present == "yes"
            totals["typed"] += bool(typed)
            print("| `%s` | %s | %s | %s |" % (e["signatures"][0] if e["signatures"] else m, present,
                                                ", ".join(typed) or "api_call", ", ".join(notes)))
        extra = sorted((live.get(cls) or set()) - set(methods))
        if extra:
            print("\nUndocumented but present in this build: %s\n" % ", ".join("`%s`" % x for x in extra))
        print()
    print("**Totals:** %(documented)d documented methods, %(live)d confirmed present on live objects, "
          "%(typed)d wrapped by typed tools (all reachable via api_call)." % totals)


if __name__ == "__main__":
    main()
